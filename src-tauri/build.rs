fn main() {
    // Tauri's Windows resource compiler requires an ICO even for `cargo check`.
    // Keep a tiny deterministic fallback in the native project so a fresh clone
    // can compile before the final branded icon is supplied by the frontend.
    let manifest_dir = std::path::PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by Cargo"),
    );
    let icon_dir = manifest_dir.join("icons");
    let icon_path = icon_dir.join("icon.ico");
    const FALLBACK_ICON: &[u8] = &[
        // ICONDIR + one ICONDIRENTRY (1x1, 32-bit, 68-byte PNG at offset 22).
        0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x20, 0x00, 0x44,
        0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, // PNG payload.
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
        0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x04, 0x00, 0x00, 0x00, 0xb5,
        0x1c, 0x0c, 0x02, 0x00, 0x00, 0x00, 0x0b, 0x49, 0x44, 0x41, 0x54, 0x78, 0xda, 0x63, 0x64,
        0xf8, 0x0f, 0x00, 0x01, 0x05, 0x01, 0x01, 0x27, 0x18, 0xe3, 0x66, 0x00, 0x00, 0x00, 0x00,
        0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
    ];
    if !icon_path.exists() {
        std::fs::create_dir_all(&icon_dir).expect("failed to create the icon directory");
        std::fs::write(&icon_path, FALLBACK_ICON).expect("failed to create the fallback icon");
    }
    tauri_build::build()
}
